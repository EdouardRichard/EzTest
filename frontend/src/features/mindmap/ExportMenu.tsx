"use client"

import { Download, Loader2 } from "lucide-react"
import type { RefObject } from "react"
import { useState } from "react"

import { mindmapApi } from "./api"
import { describeMindmapError } from "./error-messages"
import { downloadBlob, mindmapPngFilename, svgToPngBlob } from "./png-export"
import type { BaselineView, ExportFormat } from "./types"

type Exporting = ExportFormat | "png"

const SERVER_FORMATS: readonly {
  format: ExportFormat
  label: string
  testId: string
  extension: string
}[] = [
  { format: "markdown", label: "Markdown", testId: "btn-export-markdown", extension: "md" },
  { format: "mermaid", label: "Mermaid", testId: "btn-export-mermaid", extension: "mmd" },
  { format: "opml", label: "OPML", testId: "btn-export-opml", extension: "opml" },
]

const BUTTON_CLASS =
  "inline-flex items-center gap-1.5 rounded-lg border border-border bg-card px-2.5 py-1.5 text-xs font-medium text-foreground transition-colors hover:bg-muted disabled:opacity-50 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring"

export type ExportMenuProps = {
  /** P3-owned version id; never re-parsed (spec §7.1). */
  versionId: string
  /** The live canvas SVG used for the client-side PNG snapshot (spec §6.10). */
  svgRef: RefObject<SVGSVGElement | null>
  /** Prevents every export action (e.g. while the graph is still loading). */
  disabled?: boolean
  /** Version name used for the PNG filename (`{versionName}-mindmap.png`). */
  versionName?: string
  /** Frozen baseline; when present the export is bound to it (spec §6.10). */
  baseline?: BaselineView | null
}

/**
 * Export menu (spec §6.10/§9.2): Markdown/Mermaid/OPML are generated by the
 * server (`POST /export` → authenticated `GET /exports/{id}/download`), while
 * PNG is a client-side snapshot of the current canvas. Downloads use the
 * server's `Content-Disposition` filename when present and a deterministic
 * fallback otherwise. Every button is disabled while one export is in flight.
 */
export function ExportMenu({
  versionId,
  svgRef,
  disabled = false,
  versionName = "version",
  baseline = null,
}: ExportMenuProps) {
  const [exporting, setExporting] = useState<Exporting | null>(null)
  const [error, setError] = useState("")
  const [notice, setNotice] = useState("")

  const locked = disabled || exporting !== null

  async function exportServerFormat(format: ExportFormat, extension: string): Promise<void> {
    if (locked) return
    setExporting(format)
    setError("")
    setNotice("")
    try {
      const created = await mindmapApi.createExport(versionId, { format })
      const fallback =
        created.fileName !== undefined && created.fileName !== ""
          ? created.fileName
          : `mindmap-${format}.${extension}`
      const download = await mindmapApi.downloadExport(versionId, created.id, fallback)
      downloadBlob(download.blob, download.filename)
      setNotice(`已导出 ${download.filename}`)
    } catch (caught) {
      setError(describeMindmapError(caught))
    } finally {
      setExporting(null)
    }
  }

  async function exportPng(): Promise<void> {
    if (locked) return
    const svg = svgRef.current
    if (svg === null) {
      setError("画布尚未就绪，暂时无法导出 PNG。")
      return
    }

    setExporting("png")
    setError("")
    setNotice("")
    try {
      const blob = await svgToPngBlob(svg)
      const filename = mindmapPngFilename(versionName)
      downloadBlob(blob, filename)
      setNotice(`已导出 ${filename}`)
    } catch {
      setError("PNG 导出失败，请重试。")
    } finally {
      setExporting(null)
    }
  }

  return (
    <section
      aria-label="导出"
      data-testid="export-menu"
      className="min-w-0 rounded-2xl border border-border bg-card p-4"
    >
      <h2 className="text-base font-semibold">导出</h2>
      <p className="mt-0.5 text-xs text-muted-foreground">
        Markdown / Mermaid / OPML 由服务端生成；PNG 为当前画布快照。
      </p>

      <div className="mt-2 flex flex-wrap gap-1.5" aria-busy={exporting !== null}>
        {SERVER_FORMATS.map(({ format, label, testId, extension }) => (
          <button
            key={format}
            type="button"
            data-testid={testId}
            onClick={() => void exportServerFormat(format, extension)}
            disabled={locked}
            className={BUTTON_CLASS}
          >
            {exporting === format ? (
              <Loader2 className="h-3.5 w-3.5 animate-spin" aria-hidden="true" />
            ) : (
              <Download className="h-3.5 w-3.5" aria-hidden="true" />
            )}
            {exporting === format ? "导出中…" : `导出 ${label}`}
          </button>
        ))}
        <button
          type="button"
          data-testid="btn-export-png"
          onClick={() => void exportPng()}
          disabled={locked}
          className={BUTTON_CLASS}
        >
          {exporting === "png" ? (
            <Loader2 className="h-3.5 w-3.5 animate-spin" aria-hidden="true" />
          ) : (
            <Download className="h-3.5 w-3.5" aria-hidden="true" />
          )}
          {exporting === "png" ? "导出中…" : "导出 PNG"}
        </button>
      </div>

      {baseline === null ? (
        <p className="mt-2 text-[11px] text-muted-foreground">版本尚未冻结：导出为当前草稿快照。</p>
      ) : (
        <p
          data-testid="export-baseline-hint"
          className="mt-2 rounded-lg border border-sky-500/30 bg-sky-500/10 px-2.5 py-1.5 text-[11px] text-sky-700 dark:text-sky-300"
        >
          {`已绑定基线 · 导出的文件将引用该基线（${baseline.caseCount} 个用例）。`}
        </p>
      )}

      {error === "" ? null : (
        <p
          role="alert"
          className="mt-2 rounded-xl border border-destructive/30 bg-destructive/10 px-3 py-2 text-xs text-destructive"
        >
          {error}
        </p>
      )}
      {notice === "" ? null : (
        <p
          role="status"
          className="mt-2 rounded-xl border border-emerald-500/30 bg-emerald-500/10 px-3 py-2 text-xs text-emerald-700 dark:text-emerald-300"
        >
          {notice}
        </p>
      )}
    </section>
  )
}
