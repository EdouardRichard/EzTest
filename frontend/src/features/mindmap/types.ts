/**
 * DTOs for the P5 case-mindmap API (spec §7.2/§7.3/§7.4).
 *
 * ID rules (spec §7.1, D29): every mindmap ID (node/step/assertion/source/
 * anchor/run/review/finding/export) and every version/requirement ID is a
 * decimal string and must never be converted with `Number()`. P2 resource IDs
 * (`systemId`, `environmentId`, `sessionId`) keep their existing numeric type.
 * Timestamps are RFC3339 strings.
 */

import type { Version, VersionStatus } from "@/features/versions/types"

/** Stable machine-readable failure reasons carried in `error.details.reason`. */
export type MindmapErrorReason =
  | "version_state_conflict"
  | "baseline_frozen"
  | "case_revision_conflict"
  | "invalid_case_tree"
  | "no_cases"
  | "unconfirmed_requirements"
  | "requirement_not_found"
  | "requirement_not_clarified"
  | "node_not_found"
  | "step_not_found"
  | "assertion_not_found"
  | "source_not_found"
  | "anchor_not_found"
  | "run_in_progress"
  | "run_not_found"
  | "invalid_run_kind"
  | "invalid_case_proposal"
  | "blocker_findings_open"
  | "exploration_requires_environment"
  | "environment_not_allowed"
  | "code_repo_unavailable"
  | "ai_unavailable"
  | "export_format_unsupported"
  | "export_not_found"
  | "export_corrupted"
  | "graph_too_large"
  | "forbidden"

/** A mindmap node is either a structural scenario or a leaf test case. */
export type CaseNodeKind = "scenario" | "case"

/** Content origin shared by nodes, sources and (partly) steps/assertions. */
export type CaseSourceKind = "user_input" | "ai_generated" | "ai_supplement"

/** Life-cycle status mirrored from `case_node.status`. */
export type CaseNodeStatus =
  | "draft"
  | "reviewed"
  | "executed"
  | "supplemented"
  | "merged"
  | "rejected"
  | "needs_revalidation"

/** Case priority mirrored from `case_node.priority`. */
export type CasePriority = "P0" | "P1" | "P2" | "P3"

/** Steps and assertions are only ever authored by a user or generated by AI. */
export type CaseContentSource = "user_input" | "ai_generated"

/** Assertion kinds mirrored from `case_assertion.kind` (P8 adds `visual`). */
export type AssertionKind = "ui" | "api" | "db" | "text" | "visual"

/** Reference kinds accepted by `POST /nodes/{nodeId}/sources`. */
export type CaseRefKind = "requirement" | "app_model" | "ai_run" | "manual"

/** Confidence level shared by sources, anchors and impact candidates. */
export type Confidence = "high" | "medium" | "low"

/** The four agent-run kinds of spec §6.6. */
export type RunKind = "design" | "review" | "data_plan" | "explore"

/** Run status mirrored from `case_design_run.status`. */
export type RunStatus = "queued" | "running" | "done" | "failed" | "degraded"

/** Review decision accepted by `POST /review`. */
export type ReviewDecision = "approve" | "reject"

/** Review status mirrored from `case_review.status`. */
export type ReviewStatus = "draft" | "approved" | "rejected"

/** Finding categories mirrored from `case_review_finding.category`. */
export type FindingCategory =
  | "coverage"
  | "assertion"
  | "executability"
  | "duplicate"
  | "code_uncovered"
  | "other"

/** Finding severities mirrored from `case_review_finding.severity`. */
export type FindingSeverity = "blocker" | "major" | "minor" | "info"

/** Finding statuses mirrored from `case_review_finding.status`. */
export type FindingStatus = "open" | "fixed" | "dismissed"

/** Finding origin mirrored from `case_review_finding.source`. */
export type FindingSource = "ai" | "human"

/** Server-generated export formats; PNG is rendered client-side. */
export type ExportFormat = "markdown" | "mermaid" | "opml"

/** One ordered action of a case (spec §7.3). */
export type CaseStepView = {
  id: string
  seq: number
  action: string
  expected: string
  data: string
  source: CaseContentSource
}

/** One expected outcome of a case; `stepId` is optional (spec §7.3). */
export type CaseAssertionView = {
  id: string
  stepId: string | null
  kind: AssertionKind
  target: string
  expression: string
  expected: string
  source: CaseContentSource
  /** Comparison configuration when `kind === "visual"` (design spec §9.3). */
  visual?: CaseVisualAssertionView | null
}

/** Normalized screenshot crop of a visual assertion (all values 0..1). */
export type VisualRegionView = {
  x: number
  y: number
  width: number
  height: number
}

/** Comparison configuration of one `kind=visual` assertion (spec §9.3). */
export type CaseVisualAssertionView = {
  selector: string
  region: VisualRegionView | null
  threshold: number
  baselineEvidenceId: string | null
  viewportWidth: number
  viewportHeight: number
  deviceScaleFactor: number
  approvedBy: number | null
  approvedAt: string | null
  revision: number
}

/** Body of `PUT /assertions/{assertionId}/visual`; guarded by the node revision. */
export type UpdateVisualAssertionBody = {
  nodeRevision: number
  selector: string
  region?: VisualRegionView | null
  threshold: number
  viewport: { width: number; height: number }
  deviceScaleFactor: number
}

/** Body of `POST /assertions/{assertionId}/visual/baseline` (admin only). */
export type ApproveVisualBaselineBody = {
  evidenceId: string
}

/** One requirement/app-model/run/manual justification of a case (spec §7.3). */
export type CaseSourceView = {
  id: string
  refKind: CaseRefKind
  refId: string | null
  refKey: string
  source: CaseSourceKind
  confidence: Confidence
}

/** One code anchor attached to a case (`subject_kind='case'`, D37). */
export type CodeAnchorView = {
  id: string
  filePath: string
  startLine: number | null
  endLine: number | null
  confidence: Confidence
  commitSha: string | null
}

/**
 * One node of the graph response (spec §7.3). Scenarios never carry steps,
 * assertions or sources; cases always carry at least one step and assertion.
 * `anchors` is optional when the read omits `include=anchors`; the loader
 * normalizes an absent section to `[]` (see `NormalizedCaseNodeView`).
 */
export type CaseNodeView = {
  id: string
  parentId: string | null
  kind: CaseNodeKind
  title: string
  description: string
  priority: CasePriority
  preconditions: string
  testData: unknown | null
  source: CaseSourceKind
  status: CaseNodeStatus
  sortOrder: number
  revision: number
  steps: CaseStepView[]
  assertions: CaseAssertionView[]
  sources: CaseSourceView[]
  anchors?: CodeAnchorView[]
  openBlockerCount: number
}

/** One row of the requirement coverage matrix (spec §6.2/§7.3). */
export type CoverageCell = {
  requirementId: string
  caseIds: string[]
}

/** Requirement ↔ case coverage projection of `GET /mindmap` (spec §7.3). */
export type Coverage = {
  requirementIds: string[]
  uncoveredRequirementIds: string[]
  staleRequirementIds: string[]
  matrix: CoverageCell[]
}

/** The immutable frozen baseline of a version (spec §6.4). */
export type BaselineView = {
  id: string
  graphHash: string
  caseCount: number
  nodeCount: number
  frozenAt: string
  codeBaselineCommit: string | null
}

/**
 * The latest run of one kind, summarised inside the graph response. The spec
 * only guarantees `id/status/kind`; `finishedAt` (and the counts) may be
 * null/absent, and `kind` itself may be inferred from the `latestRuns` key.
 */
export type LatestRunView = {
  id: string
  kind?: RunKind
  status: RunStatus
  finishedAt?: string | null
  findingCount?: number
  blockerCount?: number
}

/** Latest run projections keyed by run kind (design/review in P5). */
export type LatestRuns = Partial<Record<RunKind, LatestRunView>>

/** One read-only "possibly affected" hint derived from P4 code analysis. */
export type ImpactCaseView = {
  caseNodeId: string
  reason: string
  confidence: Confidence
  source: string
}

/** `GET /mindmap` response (spec §7.3). */
export type MindmapGraph = {
  versionId: string
  versionStatus: VersionStatus
  /** Server-owned; the client never infers editability (spec §7.1). */
  editable: boolean
  nodes: CaseNodeView[]
  coverage: Coverage
  baseline: BaselineView | null
  latestRuns: LatestRuns
  /**
   * Optional when the read omits `include=impact` (or an older server omits
   * the key); the loader normalizes it to `[]` (see `NormalizedMindmapGraph`).
   */
  impactCases?: ImpactCaseView[]
  /** Present only when `include=findings` is requested (spec §7.3). */
  findings?: CaseFindingView[]
}

/** A node after the loader filled an absent `anchors` section with `[]`. */
export type NormalizedCaseNodeView = Omit<CaseNodeView, "anchors"> & {
  anchors: CodeAnchorView[]
}

/**
 * A graph after the loader filled the optional include sections, so consumers
 * (canvas, panels) can iterate `impactCases`/`anchors` without guards.
 */
export type NormalizedMindmapGraph = Omit<MindmapGraph, "nodes" | "impactCases"> & {
  nodes: NormalizedCaseNodeView[]
  impactCases: ImpactCaseView[]
}

/** One non-fatal run error; never carries LLM or mindmap bodies (D30). */
export type CaseRunError = {
  code: string
  message: string
}

/** A run detail/listing row; LLM input/output is never returned (spec §7.2). */
export type CaseRunView = {
  id: string
  versionId: string
  kind: RunKind
  status: RunStatus
  reason: string
  stats: Record<string, unknown> | null
  errors: CaseRunError[]
  /** P1/P2-owned IDs keep their existing numeric type (spec §7.1). */
  agentSessionId: number | null
  agentRunId: number | null
  model: string
  promptVersion: string
  createdBy: number
  createdAt: string
  startedAt: string | null
  finishedAt: string | null
}

/** One review round of a version's case mindmap (spec §6.3). */
export type CaseReviewView = {
  id: string
  versionId: string
  runId: string | null
  status: ReviewStatus
  comment: string
  reviewerId: number
  decidedBy: number | null
  decidedAt: string | null
  createdAt: string
  updatedAt: string
}

/** One review finding; `nodeId` is null for version-level findings. */
export type CaseFindingView = {
  id: string
  reviewId: string
  nodeId: string | null
  category: FindingCategory
  severity: FindingSeverity
  detail: string
  status: FindingStatus
  source: FindingSource
  createdBy: number
  createdAt: string
  updatedAt: string
}

/** One server-generated export file (D30/D38); the file itself is downloaded. */
export type CaseExportView = {
  id: string
  versionId: string
  format: ExportFormat
  nodeCount: number
  sizeBytes: number
  baselineId: string | null
  createdAt: string
  /** Lowercase hex sha256 of the file contents (D30), when the server exposes it. */
  sha256?: string
  /** Suggested download filename, when the server exposes it. */
  fileName?: string
}

/** Optional sections of the graph read (spec §7.3). */
export type MindmapInclude = "anchors" | "findings" | "impact"

/** Query for `GET /mindmap`; omitted means every section. */
export type MindmapQuery = {
  include?: MindmapInclude[]
}

/** Query for `GET /runs` (spec §7.2 endpoint 18). */
export type RunsQuery = {
  kind?: RunKind
  status?: RunStatus
  limit?: number
  cursor?: string
}

/** Query for `GET /reviews` (spec §7.2 endpoint 22). */
export type ReviewsQuery = {
  limit?: number
  cursor?: string
}

/**
 * Query for `GET /findings` (spec §7.2 endpoint 23). The endpoint responds with
 * `{data: FindingView[]}` — one flat, unpaginated array (not the cursor page
 * envelope). The shared API client unwraps `data`, so `mindmapApi.listFindings`
 * resolves to the array itself; a null `data` is the only "empty" shape and is
 * normalized to `[]` there.
 */
export type FindingsQuery = {
  status?: FindingStatus
  severity?: FindingSeverity
  nodeId?: string
}

/** Query for `GET /exports` (spec §7.2 endpoint 26). */
export type ExportsQuery = {
  format?: ExportFormat
  limit?: number
  cursor?: string
}

