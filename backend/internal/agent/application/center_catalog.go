// centerRoleByKey resolves a catalogue role. The second result is false for an
// unknown role so the HTTP layer can reject a typo instead of returning an
// empty list that looks like "no sessions".
func centerRoleByKey(key string) (CenterRole, bool) {
	for _, role := range CenterRoles() {
		if role.Role == key {
			return role, true
		}
	}
	return CenterRole{}, false
}
