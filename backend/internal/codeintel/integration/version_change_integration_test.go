// version_change_integration_test.go proves the P8 §4.2 migration on a real
// PostgreSQL database: the table shape, the (version_id, batch_id) uniqueness,
// the order.txt append and the repository's idempotent upsert plus read-only
// run_batch projection.

// TestVersionChangeMigrationAndRepository pins the version_change DDL and the
// PostgreSQL adapter against a real schema.
func TestVersionChangeMigrationAndRepository(t *testing.T) {
	pool := testutil.OpenTestDB(t)
	ctx := context.Background()

	if !tableExists(t, ctx, pool, "version_change") {
		t.Fatal("version_change table does not exist")
	}

	for _, want := range []struct {
		column   string
		dataType string
		notNull  bool
	}{
		{"id", "bigint", true},
		{"version_id", "bigint", true},
		{"batch_id", "bigint", true},
		{"base_commit", "text", true},
		{"head_commit", "text", true},
		{"history_rewritten", "boolean", true},
		{"changed_files", "integer", true},
		{"impacted_cases", "integer", true},
		{"unmapped_count", "integer", true},
		{"items", "jsonb", true},
		{"computed_at", "timestamp with time zone", true},
		{"created_at", "timestamp with time zone", true},
	} {
		assertVersionChangeColumn(t, ctx, pool, want.column, want.dataType, want.notNull)
	}

	// The id is generated by the application (D29): no sequence or default.
	var hasDefault bool
	if err := pool.QueryRow(ctx, `
		SELECT column_default IS NOT NULL
		FROM information_schema.columns
		WHERE table_schema = 'public' AND table_name = 'version_change' AND column_name = 'id'`).
		Scan(&hasDefault); err != nil {
		t.Fatalf("read version_change.id default: %v", err)
	}
	if hasDefault {
		t.Fatal("version_change.id has a default; P8 ids are application-generated")
	}

	// No cross-context foreign keys: version_id/batch_id are logical references.
	var foreignKeys int
	if err := pool.QueryRow(ctx, `
		SELECT count(*)::int FROM information_schema.table_constraints
		WHERE constraint_type = 'FOREIGN KEY' AND table_name = 'version_change'`).
		Scan(&foreignKeys); err != nil {
		t.Fatalf("count version_change foreign keys: %v", err)
	}
	if foreignKeys != 0 {
		t.Fatalf("version_change has %d foreign keys, want none", foreignKeys)
	}

	// UNIQUE (version_id, batch_id): a raw duplicate insert must fail with
	// SQLSTATE 23505 instead of storing a second snapshot.
	insertVersionChangeRow(t, ctx, pool, 9001, 7001, 11)
	_, err := pool.Exec(ctx, `
		INSERT INTO version_change
			(id, version_id, batch_id, base_commit, head_commit, items)
		VALUES ($1, $2, $3, $4, $5, '[]'::jsonb)`,
		9002, 7001, 11, seedBaseCommit, seedHeadCommit)
	var pgErr *pgconn.PgError
	if !errors.As(err, &pgErr) || pgErr.Code != "23505" {
		t.Fatalf("duplicate (version_id, batch_id) error = %v, want SQLSTATE 23505", err)
	}

	// order.txt ends with the P8 migration.
	orderRaw, err := os.ReadFile("../../db/migrations/order.txt")
	if err != nil {
		t.Fatalf("read order.txt: %v", err)
	}
	lines := make([]string, 0)
	for _, line := range strings.Split(strings.ReplaceAll(string(orderRaw), "\r\n", "\n"), "\n") {
		if trimmed := strings.TrimSpace(line); trimmed != "" {
			lines = append(lines, trimmed)
		}
	}
	if len(lines) == 0 || lines[len(lines)-1] != "codeintel_0006_version_change.sql" {
		t.Fatalf("order.txt tail = %v, want codeintel_0006_version_change.sql appended", lines)
	}

	// The repository upsert is idempotent on the unique pair: the second write
	// reports created=false, keeps the stored id and leaves a single row.
	repo := codeintelpg.NewVersionChangeRepository(pool)
	first := domain.VersionChange{
		ID: 9101, VersionID: 7002, BatchID: 21,
		BaseCommit: seedBaseCommit, HeadCommit: seedHeadCommit,
		ChangedFiles: 2, ImpactedCases: 1, UnmappedCount: 1,
		Items: []domain.VersionChangeItem{{
			File: "src/api/refund.ts", ChangeKind: domain.VersionChangeModified,
			Subjects: []domain.VersionChangeSubject{{Kind: domain.KindAPI, Name: "POST /api/refund"}},
			CaseIDs:  []string{"501"},
		}},
		ComputedAt: time.Date(2026, 10, 29, 12, 0, 0, 0, time.UTC),
	}
	stored, created, err := repo.Upsert(ctx, first)
	if err != nil {
		t.Fatalf("Upsert(first): %v", err)
	}
	if !created || stored.ID != first.ID {
		t.Fatalf("Upsert(first) = created %v id %d, want created true id %d", created, stored.ID, first.ID)
	}
	second := first
	second.ID = 9102
	second.ChangedFiles = 99
	storedAgain, createdAgain, err := repo.Upsert(ctx, second)
	if err != nil {
		t.Fatalf("Upsert(second): %v", err)
	}
	if createdAgain {
		t.Fatal("Upsert(second) created a second row; the unique pair must win")
	}
	if storedAgain.ID != first.ID || storedAgain.ChangedFiles != first.ChangedFiles {
		t.Fatalf("Upsert(second) returned %+v, want the stored first snapshot", storedAgain)
	}
	var snapshots int
	if err := pool.QueryRow(ctx,
		`SELECT count(*)::int FROM version_change WHERE version_id = 7002 AND batch_id = 21`).
		Scan(&snapshots); err != nil {
		t.Fatalf("count snapshots: %v", err)
	}
	if snapshots != 1 {
		t.Fatalf("snapshots = %d, want 1 after a repeated upsert", snapshots)
	}
	listed, err := repo.ListByVersion(ctx, 7002)
	if err != nil {
		t.Fatalf("ListByVersion: %v", err)
	}
	if len(listed) != 1 || listed[0].ID != first.ID || len(listed[0].Items) != 1 ||
		listed[0].Items[0].CaseIDs[0] != "501" {
		t.Fatalf("ListByVersion = %+v", listed)
	}

	// The batch projection is read-only over the execution context's run_batch.
	insertRunBatchRow(t, ctx, pool, 9301, 7002, 1, "done", "baseline", false)
	insertRunBatchRow(t, ctx, pool, 9302, 7002, 2, "done", "incremental", true)
	batches, err := repo.ListBatches(ctx, 7002)
	if err != nil {
		t.Fatalf("ListBatches: %v", err)
	}
	if len(batches) != 2 || batches[0].BatchNo != 1 || batches[1].BatchNo != 2 {
		t.Fatalf("ListBatches = %+v, want batch 1 then batch 2", batches)
	}
	if batches[1].BaseFallbackReason != "history_rewritten" {
		t.Fatalf("batch 2 fallback = %q, want history_rewritten", batches[1].BaseFallbackReason)
	}
	if batches[1].CodeBaselineCommit != seedBaseCommit || batches[1].HeadCommit != seedHeadCommit {
		t.Fatalf("batch 2 commits = %q..%q", batches[1].CodeBaselineCommit, batches[1].HeadCommit)
	}
}

// assertVersionChangeColumn proves one version_change column exists with the
// spec type and nullability.
func assertVersionChangeColumn(t *testing.T, ctx context.Context, pool *pgxpool.Pool, column, wantType string, wantNotNull bool) {
	t.Helper()
	var dataType, isNullable string
	err := pool.QueryRow(ctx, `
		SELECT data_type, is_nullable
		FROM information_schema.columns
		WHERE table_schema = 'public' AND table_name = 'version_change' AND column_name = $1`,
		column).Scan(&dataType, &isNullable)
	if err != nil {
		t.Errorf("version_change.%s does not exist: %v", column, err)
		return
	}
	if dataType != wantType {
		t.Errorf("version_change.%s type = %q, want %q", column, dataType, wantType)
	}
	if notNull := isNullable == "NO"; notNull != wantNotNull {
		t.Errorf("version_change.%s notNull = %v, want %v", column, notNull, wantNotNull)
	}
}

// insertVersionChangeRow inserts one minimal snapshot row.
func insertVersionChangeRow(t *testing.T, ctx context.Context, pool *pgxpool.Pool, id, versionID, batchID int64) {
	t.Helper()
	if _, err := pool.Exec(ctx, `
		INSERT INTO version_change
			(id, version_id, batch_id, base_commit, head_commit, items)
		VALUES ($1, $2, $3, $4, $5, '[]'::jsonb)`,
		id, versionID, batchID, seedBaseCommit, seedHeadCommit); err != nil {
		t.Fatalf("insert version_change %d: %v", id, err)
	}
}

// insertRunBatchRow inserts one minimal run_batch row for the projection read.
func insertRunBatchRow(t *testing.T, ctx context.Context, pool *pgxpool.Pool, id, versionID int64, batchNo int, status, kind string, rewritten bool) {
	t.Helper()
	fallback := ""
	if rewritten {
		fallback = "history_rewritten"
	}
	if _, err := pool.Exec(ctx, `
		INSERT INTO run_batch
			(id, version_id, batch_no, status, baseline_hash, graph_hash, kind,
			 base_fallback_reason, code_baseline_commit, head_commit, created_by)
		VALUES ($1, $2, $3, $4, $5, $5, $6, $7, $8, $9, 1)`,
		id, versionID, batchNo, status, strings.Repeat("a", 64), kind,
		fallback, seedBaseCommit, seedHeadCommit); err != nil {
		t.Fatalf("insert run_batch %d: %v", id, err)
	}
}
