// Package domain holds the P5 mindmap context's entities, invariants and pure
// helpers. It has no dependency on infrastructure, HTTP or other contexts: the
// application layer depends on it, never the other way round.
package domain

import "time"

// Node kinds, mirrored from the case_node.kind CHECK constraint.
const (
	NodeKindScenario = "scenario"
	NodeKindCase     = "case"
)

// Content sources, mirrored from the source CHECK constraints. Steps and
// assertions only accept the user_input/ai_generated subset.
const (
	NodeSourceUserInput    = "user_input"
	NodeSourceAIGenerated  = "ai_generated"
	NodeSourceAISupplement = "ai_supplement"
)

// Node life-cycle statuses, mirrored from the case_node.status CHECK
// constraint.
const (
	NodeStatusDraft             = "draft"
	NodeStatusReviewed          = "reviewed"
	NodeStatusExecuted          = "executed"
	NodeStatusSupplemented      = "supplemented"
	NodeStatusMerged            = "merged"
	NodeStatusRejected          = "rejected"
	NodeStatusNeedsRevalidation = "needs_revalidation"
)

// Priorities, mirrored from the case_node.priority CHECK constraint.
const (
	PriorityP0 = "P0"
	PriorityP1 = "P1"
	PriorityP2 = "P2"
	PriorityP3 = "P3"
)

// CaseNode is one node of a version's case mindmap: a structural scenario or a
// leaf test case. IDs are Snowflake values generated by the application
// (D29); the database has no sequence or default for them.
type CaseNode struct {
	ID            int64
	VersionID     int64
	ParentID      *int64
	Kind          string
	Title         string
	Description   string
	Priority      string
	Preconditions string
	TestData      []byte // JSONB
	Source        string
	Status        string
	SortOrder     int
	Revision      int
	CreatedBy     int64
	UpdatedBy     int64
	CreatedAt     time.Time
	UpdatedAt     time.Time
}
