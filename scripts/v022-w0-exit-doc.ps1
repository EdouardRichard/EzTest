#requires -Version 5.1
<#
.SYNOPSIS
    Writes the W0 EXIT.md from machine evidence for scripts/v022-w0-exit.ps1.

.DESCRIPTION
    The W0 exit gate refuses to sign an EXIT.md that still carries a failing
    marker from an older HEAD. This helper rewrites EXIT.md from the fresh
    run/verdict.json (and, at Stage=final, from run/exit/checks.json) instead of
    leaving the stale note in place.

    It writes nothing unless run/verdict.json is green: flowExit=0, redCount=0,
    dbChecks.red empty, every zero-data counter > 0 and emptyScopes=0. Exit code
    3 means "not written" and the existing file is left untouched.

    Stage=precheck produces a short document that replaces the stale note before
    the gate's pre-check; it never claims that the verification commands ran.
    Stage=final requires run/exit/checks.json with an empty failures list and
    includes the seven check results and the post-run verdict.

.NOTES
    Windows PowerShell 5.1 compatible. ASCII only; the output is written as
    UTF-8 without BOM.
#>
param(
    [Parameter(Mandatory = $true)][string]$VerdictPath,
    [Parameter(Mandatory = $true)][string]$OutPath,
    [string]$ChecksPath = '',
    [ValidateSet('precheck', 'final')][string]$Stage = 'final'
)

$ErrorActionPreference = 'Stop'

function Write-Utf8([string]$Path, [string]$Text) {
    [System.IO.File]::WriteAllText($Path, $Text, (New-Object System.Text.UTF8Encoding($false)))
}

function Get-TrackedHead {
    $head = ''
    try { $head = (& git rev-parse HEAD 2>$null | Out-String).Trim() } catch { }
    return $head
}

$verdict = $null
try {
    $verdict = Get-Content -LiteralPath $VerdictPath -Raw -Encoding UTF8 | ConvertFrom-Json
} catch {
    Write-Host "W0 EXIT.md: not written; cannot read $VerdictPath ($($_.Exception.Message))"
    exit 3
}

$zeroDataKeys = @(
    'completedRuns', 'planItems', 'planEvents', 'facts', 'waves',
    'doneExtractions', 'doneImages', 'versionCompleted',
    'stageEventKinds', 'evidenceRows'
)
$problems = New-Object System.Collections.Generic.List[string]
if ([int]$verdict.flowExit -ne 0) { $problems.Add("flowExit=$($verdict.flowExit)") }
if ([int]$verdict.redCount -ne 0) { $problems.Add("redCount=$($verdict.redCount)") }
if (@($verdict.dbChecks.red).Count -ne 0) {
    $problems.Add("dbChecks.red has $(@($verdict.dbChecks.red).Count) entr(ies)")
}
foreach ($key in $zeroDataKeys) {
    if ([int]$verdict.dbChecks.$key -le 0) { $problems.Add("dbChecks.$key=$($verdict.dbChecks.$key)") }
}
if ([int]$verdict.dbChecks.emptyScopes -ne 0) {
    $problems.Add("dbChecks.emptyScopes=$($verdict.dbChecks.emptyScopes)")
}
if ($problems.Count -gt 0) {
    Write-Host "W0 EXIT.md: not written; run/verdict.json is not green: $($problems -join '; ')"
    exit 3
}

$checks = @()
$checkFailures = @()
if ($ChecksPath) {
    if (-not (Test-Path -LiteralPath $ChecksPath)) {
        Write-Host "W0 EXIT.md: not written; missing check summary $ChecksPath"
        exit 3
    }
    try {
        $checkSummary = Get-Content -LiteralPath $ChecksPath -Raw -Encoding UTF8 | ConvertFrom-Json
    } catch {
        Write-Host "W0 EXIT.md: not written; cannot parse $ChecksPath ($($_.Exception.Message))"
        exit 3
    }
    $checks = @($checkSummary.checks)
    $checkFailures = @($checkSummary.failures)
}
if ($Stage -eq 'final') {
    if (-not $ChecksPath) {
        Write-Host 'W0 EXIT.md: not written; Stage=final needs -ChecksPath'
        exit 3
    }
    if ($checks.Count -eq 0) {
        Write-Host 'W0 EXIT.md: not written; the check summary records no checks'
        exit 3
    }
    if ($checkFailures.Count -ne 0) {
        Write-Host "W0 EXIT.md: not written; the check summary has failures: $($checkFailures -join '; ')"
        exit 3
    }
    foreach ($check in $checks) {
        if ([int]$check.exitCode -ne 0) {
            Write-Host "W0 EXIT.md: not written; check $($check.id) exited $($check.exitCode)"
            exit 3
        }
    }
}

$tick = [char]96
$head = Get-TrackedHead
$generatedAt = Get-Date -Format 'yyyy-MM-dd HH:mm:ss zzz'
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('# EzTest v0.22 W0 - Exit verification (Task 39)')
$lines.Add('')
if ($Stage -eq 'precheck') {
    $lines.Add('> Regenerated by scripts/v022-w0-exit.ps1 from the fresh run/verdict.json because the')
    $lines.Add('> previous copy still carried a failing note from an older HEAD. The gate re-runs its')
    $lines.Add('> verification commands after this regeneration and rewrites this file with their')
    $lines.Add('> results only when they pass.')
} else {
    $lines.Add('> Machine-generated by scripts/v022-w0-exit.ps1 when the gate passed. The numbers')
    $lines.Add('> below are read from run/verdict.json and run/exit/checks.json; nothing here is')
    $lines.Add('> copied from prose.')
}
$lines.Add('')
$lines.Add("- **Date:** $generatedAt (Asia/Shanghai)")
$lines.Add("- **HEAD at verification:** $tick$head$tick")
$lines.Add('- **Verifier:** W0 exit gate (scripts/v022-w0-exit.ps1)')
if ($Stage -eq 'precheck') {
    $lines.Add('- **Status:** fresh verdict green; the verification commands are running now and are not signed off by this copy.')
} else {
    $lines.Add('- **Status: PASS - 0 failing checks.** Machine summary: run/exit/checks.json (failures: []).')
}
$lines.Add('- **Gate command:** powershell.exe -NoProfile -ExecutionPolicy Bypass -File scripts\v022-w0-exit.ps1')
$lines.Add('- **Evidence root:** docs/version-V0.22/acceptance/evidence/w0/run/')
$lines.Add('')

if ($Stage -eq 'final') {
    $lines.Add('## 1. Gate results')
    $lines.Add('')
    $lines.Add('| # | Check | Command | Exit | Duration | Log |')
    $lines.Add('| --- | --- | --- | --- | --- | --- |')
    $index = 0
    foreach ($check in $checks) {
        $index++
        $lines.Add("| $index | $($check.id) | $tick$($check.command)$tick | $($check.exitCode) | $($check.durationSeconds)s | $tick$($check.log)$tick |")
    }
    $lines.Add('')
    $lines.Add("run/exit/checks.json records $($checks.Count) checks, all exit 0, failures: [].")
    $lines.Add('')
}

$section = if ($Stage -eq 'final') { 2 } else { 1 }
$lines.Add("## $section. Verdict replay")
$section++
$lines.Add('')
$lines.Add("run/verdict.json: flowExit=$([int]$verdict.flowExit), redCount=$([int]$verdict.redCount), dbChecks.red entries=$(@($verdict.dbChecks.red).Count), emptyScopes=$([int]$verdict.dbChecks.emptyScopes).")
$lines.Add('')
$lines.Add('| counter | value |')
$lines.Add('| --- | --- |')
foreach ($key in $zeroDataKeys) {
    $lines.Add("| $key | $([int64]$verdict.dbChecks.$key) |")
}
$lines.Add("| emptyScopes | $([int]$verdict.dbChecks.emptyScopes) |")
$lines.Add('')

$lines.Add("## $section. Scope of this certification")
$section++
$lines.Add('')
$lines.Add('The W0 exit item matrix (spec section 11.1 items 1-10) and the 14-issue matrix')
$lines.Add('are carried by REPORT.md and run/result.json. This gate re-runs the backend unit,')
$lines.Add('serialized integration, frontend unit, frontend typecheck and both contract')
$lines.Add('commands, then replays the fresh verdict with v022-w0-regression.ps1 -ReuseFlow')
$lines.Add('and re-reads run/verdict.json afterwards; those results are the table above.')
$lines.Add('')

$lines.Add("## $section. Final certification")
$section++
$lines.Add('')
if ($Stage -eq 'precheck') {
    $lines.Add('This copy only replaces the stale failing note before the pre-check. The gate is')
    $lines.Add('re-running the verification commands now; a green run rewrites this file with the')
    $lines.Add('check results and the post-run verdict.')
} else {
    $lines.Add("powershell.exe -NoProfile -ExecutionPolicy Bypass -File scripts\v022-w0-exit.ps1")
    $lines.Add("exited with W0 EXIT: PASS; all $($checks.Count) checks exit 0 and run/exit/checks.json")
    $lines.Add('has an empty failures list. W0 is signed off at the HEAD recorded above.')
}
$lines.Add('')

Write-Utf8 $OutPath (($lines -join "`r`n") + "`r`n")
Write-Host "W0 EXIT.md: $Stage document written to $OutPath"
exit 0
